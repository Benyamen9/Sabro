// Serves the web fonts from this site instead of Google (owner, 2026-11-02: faster loading).
// The page's first paint used to wait for fonts.googleapis.com, a second host to reach, once
// 7.6 s on a cold visit. This downloads Google's own woff2 files and @font-face rules once,
// into public/fonts/ and app/assets/css/fonts.css, which are committed. The unicode-range
// subsets are kept, so a browser still fetches only the files a page uses.
//
// Re-run after changing FONTS below:   node scripts/self-host-fonts.mjs
// The same script is in all six frontends; each lists its own families.
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const FONTS = 'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400&family=Noto+Sans+Syriac:wght@400;500;700&family=Noto+Sans+Syriac+Eastern:wght@400;500;700&family=Noto+Sans+Syriac+Western:wght@400;500;700&display=swap'

// A current Chrome, so Google answers with woff2 and unicode-range subsets.
const USER_AGENT = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const fontDir = join(root, 'public', 'fonts')
const cssFile = join(root, 'app', 'assets', 'css', 'fonts.css')

const response = await fetch(FONTS, { headers: { 'User-Agent': USER_AGENT } })
if (!response.ok) throw new Error(`Google Fonts answered ${response.status}`)
let css = await response.text()

await rm(fontDir, { recursive: true, force: true })
await mkdir(fontDir, { recursive: true })

const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))]
for (const url of urls) {
  // /s/notosanssyriac/v18/Ktk2….woff2 → notosanssyriac-v18-Ktk2….woff2
  const name = new URL(url).pathname.replace(/^\/s\//, '').replaceAll('/', '-')
  const file = await fetch(url)
  if (!file.ok) throw new Error(`${url} answered ${file.status}`)
  await writeFile(join(fontDir, name), Buffer.from(await file.arrayBuffer()))
  css = css.replaceAll(url, `/fonts/${name}`)
}

const header = `/* Generated by scripts/self-host-fonts.mjs from Google Fonts. Do not edit by hand. */\n`
await writeFile(cssFile, header + css)
console.log(`${urls.length} font files in public/fonts/, rules in app/assets/css/fonts.css`)
console.log((await readdir(fontDir)).length === urls.length ? 'ok' : 'file count mismatch')
